"""Puertos: lo que la lógica de aplicación necesita del exterior.

Los servicios dependen de estos Protocols (inversión de dependencias); las
implementaciones concretas (SQLAlchemy, JWT, reloj del sistema) viven en
`infrastructure` y en las pruebas se sustituyen por falsos.
"""

from __future__ import annotations

from datetime import datetime
from typing import Protocol

from app.domain.entities import Appointment, Doctor, Patient, User


class UserRepository(Protocol):
    def add(self, user: User) -> User: ...
    def get_by_email(self, email: str) -> User | None: ...
    def get(self, user_id: int) -> User | None: ...


class PatientRepository(Protocol):
    def add(self, patient: Patient) -> Patient: ...
    def get(self, patient_id: int) -> Patient | None: ...
    def get_by_document(self, document_id: str) -> Patient | None: ...
    def update(self, patient: Patient) -> Patient: ...
    def list(self, *, query: str | None, limit: int, offset: int) -> list[Patient]: ...


class DoctorRepository(Protocol):
    def add(self, doctor: Doctor) -> Doctor: ...
    def get(self, doctor_id: int) -> Doctor | None: ...
    def list(self, *, specialty: str | None, limit: int, offset: int) -> list[Doctor]: ...


class AppointmentRepository(Protocol):
    def add(self, appointment: Appointment) -> Appointment: ...
    def get(self, appointment_id: int) -> Appointment | None: ...
    def update(self, appointment: Appointment) -> Appointment: ...
    def list(
        self,
        *,
        doctor_id: int | None,
        patient_id: int | None,
        start: datetime | None,
        end: datetime | None,
        limit: int,
        offset: int,
    ) -> list[Appointment]: ...
    def find_scheduled_overlapping(
        self, *, start: datetime, end: datetime, doctor_id: int | None, patient_id: int | None
    ) -> list[Appointment]: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...


class TokenService(Protocol):
    def issue(self, user_id: int) -> str: ...
    def read(self, token: str) -> int: ...
